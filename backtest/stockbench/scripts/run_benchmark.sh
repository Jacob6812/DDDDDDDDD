#!/usr/bin/env bash
set -euo pipefail

# DarwinTrade end-to-end backtest runner.
# LLM credentials come from <repo>/.env (LLM_BASE_URL / LLM_API_KEY / LLM_MODEL).

START_DATE="${START_DATE:-2025-03-01}"
END_DATE="${END_DATE:-2025-06-30}"

# Resolve repo root (this script lives at backtest/scripts/)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

CONFIG_PATH="${CONFIG_PATH:-${REPO_ROOT}/backtest/config_darwintrade.yaml}"
APP_MOD="backtest.cli"

RESUME_ENABLED="${RESUME_ENABLED:-1}"
RESUME_SUMMARY="${RESUME_SUMMARY:-}"
RESUME_DATE="${RESUME_DATE:-}"
RUN_ID="${RUN_ID:-}"

OUTPUT_DIR="${OUTPUT_DIR:-${REPO_ROOT}/storage/reports/backtest}"
LOG_DIR="${LOG_DIR:-${REPO_ROOT}/storage/logs}"

log_info()    { echo "[INFO] $(date '+%Y-%m-%d %H:%M:%S') - $1"; }
log_error()   { echo "[ERROR] $(date '+%Y-%m-%d %H:%M:%S') - $1" >&2; }
log_success() { echo "[SUCCESS] $(date '+%Y-%m-%d %H:%M:%S') - $1"; }

check_prerequisites() {
    if [[ ! -f "${CONFIG_PATH}" ]]; then
        log_error "Configuration file not found: ${CONFIG_PATH}"
        exit 1
    fi
    if ! python -c "import importlib; importlib.import_module('${APP_MOD}')" 2>/dev/null; then
        log_error "Python module not found: ${APP_MOD}"
        exit 1
    fi
    mkdir -p "${OUTPUT_DIR}" "${LOG_DIR}"
}

build_resume_opts() {
    if [[ "${RESUME_ENABLED}" != "1" ]]; then
        printf '%s' "--no-resume"
        return
    fi
    local OPTS="--resume"
    [[ -n "${RESUME_SUMMARY}" ]] && OPTS+=" --resume-summary \"${RESUME_SUMMARY}\""
    [[ -n "${RESUME_DATE}" ]]    && OPTS+=" --resume-date \"${RESUME_DATE}\""
    printf '%s' "${OPTS}"
}

while [[ $# -gt 0 ]]; do
    case $1 in
        --start-date)      START_DATE="$2";       shift 2 ;;
        --end-date)        END_DATE="$2";         shift 2 ;;
        --run-id)          RUN_ID="$2";           shift 2 ;;
        --resume-summary)  RESUME_SUMMARY="$2";   shift 2 ;;
        --resume-date)     RESUME_DATE="$2";      shift 2 ;;
        --resume)          RESUME_ENABLED="1";    shift ;;
        --no-resume)       RESUME_ENABLED="0";    shift ;;
        --help|-h)
            cat <<EOF
Usage: $0 [options]

Options:
  --start-date DATE     Start date (default: ${START_DATE})
  --end-date DATE       End date (default: ${END_DATE})
  --run-id ID           Output run_id (auto-generated by default)
  --resume              Enable resume (default)
  --no-resume           Disable resume
  --resume-summary PATH Resume from a daily_run_summary.jsonl path
  --resume-date DATE    Resume from a specific trade date

LLM credentials are read from <repo>/.env:
  LLM_BASE_URL, LLM_API_KEY, LLM_MODEL
EOF
            exit 0
            ;;
        *)
            log_error "Unknown parameter: $1"
            exit 1
            ;;
    esac
done

check_prerequisites

EFFECTIVE_RUN_ID="${RUN_ID:-darwintrade_$(date +%Y%m%d_%H%M%S)}"
LOG_FILE="${LOG_DIR}/${EFFECTIVE_RUN_ID}.log"
RESUME_OPTS="$(build_resume_opts)"

log_info "DarwinTrade backtest"
log_info "  run_id   : ${EFFECTIVE_RUN_ID}"
log_info "  range    : ${START_DATE} → ${END_DATE}"
log_info "  config   : ${CONFIG_PATH}"
log_info "  log file : ${LOG_FILE}"

CMD="python -m ${APP_MOD} \
    --cfg \"${CONFIG_PATH}\" \
    --start \"${START_DATE}\" --end \"${END_DATE}\" \
    --run-id \"${EFFECTIVE_RUN_ID}\" \
    ${RESUME_OPTS}"

START_TIME=$(date +%s)
if eval "${CMD}" > "${LOG_FILE}" 2>&1; then
    DURATION=$(( $(date +%s) - START_TIME ))
    log_success "Backtest completed in ${DURATION}s — ${LOG_FILE}"
else
    DURATION=$(( $(date +%s) - START_TIME ))
    log_error "Backtest failed after ${DURATION}s — see ${LOG_FILE}"
    exit 1
fi
